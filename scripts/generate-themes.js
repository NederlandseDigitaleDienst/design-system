#!/usr/bin/env node
/**
 * Generate one stylesheet per theme, plus one with all of them.
 *
 * Reads scripts/reference-colors.json and the palettes in
 * src/assets/styles/colors.generated.css, and writes
 * src/assets/styles/themes/<name>.css and src/assets/styles/themes.css.
 * The rules live in scripts/lib/themes.js.
 *
 * Run after changing the reference colors or the palettes:
 *   npm run generate:themes
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { neutralReference, parsePalettes, propertyOrder, selectionGrounds, themeColors, themeCss } from './lib/themes.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STYLES = join(ROOT, 'src/assets/styles');
const OUTPUT_DIR = join(STYLES, 'themes');

const references = JSON.parse(readFileSync(join(ROOT, 'scripts/reference-colors.json'), 'utf8'));
const palettes = parsePalettes(readFileSync(join(STYLES, 'colors.generated.css'), 'utf8'));

const header = (what) => `/**
 * ${what}
 *
 * Generated by scripts/generate-themes.js from scripts/reference-colors.json.
 * DO NOT EDIT BY HAND — run \`npm run generate:themes\` to regenerate.
 */

`;

rmSync(OUTPUT_DIR, { recursive: true, force: true });
mkdirSync(OUTPUT_DIR, { recursive: true });

const coolgray = references.find((c) => c.neutral).hex;
const grounds = selectionGrounds(palettes.get('coolgray'));
const order = propertyOrder(readFileSync(join(STYLES, 'variables.css'), 'utf8'));
const neutralScale = (hex) =>
	execFileSync('python3', [join(ROOT, 'scripts/generate-palette.py'), neutralReference(coolgray, hex), 'neutral', '--neutral'], { encoding: 'utf8' });

const rules = themeColors(references).map(({ name, hex }) => {
	const css = themeCss(name, palettes.get(name), hex, { grounds, neutral: neutralScale(hex), order });
	writeFileSync(join(OUTPUT_DIR, `${name}.css`), header(`NLDD theme "${name}": set data-nldd-theme="${name}" on <html>.`) + css);
	return css;
});

writeFileSync(join(STYLES, 'themes.css'), header('All NLDD themes: set data-nldd-theme on <html> to pick one.') + rules.join('\n'));

console.log(`Generated ${rules.length} themes → src/assets/styles/themes/ and themes.css`);
