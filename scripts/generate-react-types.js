/**
 * Generates dist/types/react.d.ts from custom-elements.json.
 *
 * Declares every nldd-* tag in React's JSX.IntrinsicElements, so a React app
 * gets its attributes checked and does not have to write these types itself.
 *
 * The declarations hold for React 18 and 19 alike:
 *
 *   - Attributes only, in their kebab form. React 18 writes every prop on a
 *     custom element as an attribute, so a camelCase property name reaches the
 *     element as an attribute it does not know. React 19 writes a prop that is
 *     not a property as an attribute too, so the kebab form works in both.
 *   - A boolean attribute takes `true` or nothing. React 18 writes `false` as the
 *     text "false", and a boolean attribute is on as soon as it is there, so
 *     `disabled={busy}` always disables. With `true | undefined` the compiler
 *     asks for `disabled={busy || undefined}`, which leaves the attribute off.
 *   - No properties without an attribute, and no events. React 18 cannot set
 *     either; use a ref and addEventListener for those.
 *
 * Usage: node scripts/generate-react-types.js
 */

import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const manifestPath = resolve(repoRoot, 'custom-elements.json');
const outputPath = resolve(repoRoot, 'dist/types/react.d.ts');

const PACKAGE = '@nldd/design-system';

const toCamel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const toPascal = (name) => {
	const camel = toCamel(name);
	return camel.charAt(0).toUpperCase() + camel.slice(1);
};

/** One JSDoc line, so hovering a prop in an editor shows what it does. */
function comment(text) {
	return text ? `\n\t/** ${String(text).replace(/\s+/g, ' ').replace(/\*\//g, '*\\/')} */` : '';
}

/** A boolean attribute, also one typed `boolean | undefined` for a third state. */
function isBoolean(attribute) {
	const text = attribute.type?.text ?? '';
	const parts = text.split('|').map((part) => part.trim()).filter((part) => part && part !== 'undefined');
	return parts.length === 1 && parts[0] === 'boolean';
}

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const components = [];
for (const module of manifest.modules ?? []) {
	const subpath = module.path.split('/').pop().replace(/\.ts$/, '');
	for (const declaration of module.declarations ?? []) {
		if (!declaration.customElement || !declaration.tagName) continue;
		// A class without a name of its own (nldd-button-bar-divider) has no type to
		// import, so it is typed as a plain element with string attributes.
		const anonymous = /^anonymous_/.test(declaration.name);
		const propsName = `${toPascal(declaration.tagName)}Props`;
		components.push({ ...declaration, subpath, anonymous, propsName });
	}
}
components.sort((a, b) => a.tagName.localeCompare(b.tagName));

const imports = components
	.filter((c) => !c.anonymous)
	.map((c) => `import type { ${c.name} } from '${PACKAGE}/${c.subpath}';`)
	.join('\n');

const propsTypes = components
	.map((component) => {
		const lines = [];
		const seen = new Set();
		for (const attribute of component.attributes ?? []) {
			if (seen.has(attribute.name)) continue;
			seen.add(attribute.name);
			const field = attribute.fieldName ?? toCamel(attribute.name);
			const type = isBoolean(attribute) ? 'true' : component.anonymous ? 'string' : `${component.name}['${field}']`;
			lines.push(`${comment(attribute.description)}\n\t'${attribute.name}'?: ${type};`);
		}
		return `type ${component.propsName} = {${lines.join('')}\n};`;
	})
	.join('\n\n');

const entries = components
	.map((c) => `${comment(c.description).replace(/\n\t/g, '\n\t\t\t')}\n\t\t\t'${c.tagName}': NlddElement<${c.anonymous ? 'HTMLElement' : c.name}, ${c.propsName}>;`)
	.join('');

const output = `// Generated by scripts/generate-react-types.js. Do not edit.
//
// Declares every nldd-* element in React's JSX. Import it once in your project
// (for example in a .d.ts file that your tsconfig includes):
//
//     import '${PACKAGE}/react';
//
// Attributes are written as in markup (accessible-label), which works in React
// 18 and 19. A boolean takes true or nothing: write disabled={busy || undefined},
// since React 18 turns false into the text "false", which reads as on. Events
// and properties without an attribute go through a ref.

import type * as React from 'react';
${imports}

/** The element's own attributes, on top of what every HTML element takes. Not
 *  named Element: inside namespace JSX that name is React's JSX.Element. */
type NlddElement<E, P> = Omit<React.DetailedHTMLProps<React.HTMLAttributes<E>, E>, keyof P> & P;

${propsTypes}

declare module 'react' {
	namespace JSX {
		interface IntrinsicElements {${entries}
		}
	}
}

export {};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output);
console.log(`Wrote ${outputPath.replace(`${repoRoot}/`, '')} (${components.length} elements)`);
