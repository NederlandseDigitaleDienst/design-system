import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GENERATED, inOrder } from './generated-files.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const scripts = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')).scripts;

test('every entry names an npm script that exists', () => {
	for (const entry of GENERATED) assert.ok(scripts[entry.script], `${entry.script} is not in package.json`);
});

test('the reference comes after the manifest it reads', () => {
	const order = inOrder().map((entry) => entry.script);
	assert.ok(order.indexOf('generate:cem') < order.indexOf('generate:component-reference'));
});

test('inOrder keeps the table order and puts a dependency first', () => {
	const order = inOrder([{ script: 'b', after: ['a'] }, { script: 'c' }, { script: 'a' }]).map((entry) => entry.script);
	assert.deepEqual(order, ['a', 'b', 'c']);
});

test('inOrder refuses an unknown dependency and a cycle', () => {
	assert.throws(() => inOrder([{ script: 'b', after: ['a'] }]), /produces nothing/);
	assert.throws(() => inOrder([{ script: 'a', after: ['b'] }, { script: 'b', after: ['a'] }]), /cycle/);
});

test('every tracked file that says it is generated has an entry', () => {
	const covered = (path) => GENERATED.some((entry) => entry.files.some((file) => path === file || path.startsWith(`${file}/`)));
	const says = (path) => {
		if (/\.generated\./.test(path)) return true;
		const head = readFileSync(resolve(root, path), 'utf8').slice(0, 300);
		return /GEGENEREERD BESTAND|GENERATED by scripts\//.test(head);
	};
	const missing = execSync('git ls-files', { cwd: root, encoding: 'utf8' })
		.split('\n')
		.filter((path) => /\.(css|ts|js|json|md|yml)$/.test(path) && !path.startsWith('scripts/'))
		.filter(says)
		.filter((path) => !covered(path));
	assert.deepEqual(missing, []);
});
