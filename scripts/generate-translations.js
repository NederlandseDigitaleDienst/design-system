/**
 * Generates src/translations/nl.generated.ts: every component's Dutch defaults
 * in one object, and the TranslationKey type that goes with it.
 *
 * The defaults stay in a {name}.i18n.ts next to each component, so a consumer
 * that imports one component gets only its texts. This file is the overview on
 * top: the template a translator copies, the type that makes the shipped
 * en-US complete, and the list setTranslations() checks unknown keys against.
 *
 * Usage: node scripts/generate-translations.js
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { resolve, dirname, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const componentsDir = join(root, 'src/components');
const outFile = join(root, 'src/translations/nl.generated.ts');

function findI18nFiles(dir) {
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) return findI18nFiles(path);
		return name.endsWith('.i18n.ts') ? [path] : [];
	});
}

const entries = findI18nFiles(componentsDir)
	.map((file) => {
		const match = readFileSync(file, 'utf-8').match(/export const (nldd\w+Translations)\s*=/);
		if (!match) throw new Error(`No nldd…Translations export in ${relative(root, file)}`);
		const importPath = relative(dirname(outFile), file).replace(/\.ts$/, '.js');
		return { name: match[1], importPath };
	})
	.sort((a, b) => a.importPath.localeCompare(b.importPath));

const content = `// GENERATED by scripts/generate-translations.js — do not edit by hand.
// Regenerate with: npm run generate:translations

${entries.map(({ name, importPath }) => `import { ${name} } from '${importPath}';`).join('\n')}

/** Every text in the package with its Dutch default. */
export const nl = {
${entries.map(({ name }) => `	...${name},`).join('\n')}
};

/** Every translation key a component knows. */
export type TranslationKey = keyof typeof nl;

export default nl;
`;

writeFileSync(outFile, content, 'utf-8');
console.log(`Wrote ${relative(root, outFile)} (${entries.length} components)`);
