/**
 * Generates src/utilities/autoloader.generated.ts from custom-elements.json.
 *
 * One loader per nldd-* tag: a dynamic import of the module that defines it.
 * The autoloader calls it the first time an undefined element with that tag
 * appears, so a page loads only the components it shows. A bundler splits each
 * import into a chunk of its own; so does the standalone build in dist/cdn.
 *
 * Committed, like the lint data, so the autoloader builds without the manifest.
 *
 * Usage: node scripts/generate-autoloader.js
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const manifest = JSON.parse(readFileSync(resolve(repoRoot, 'custom-elements.json'), 'utf8'));
const outputPath = resolve(repoRoot, 'src/utilities/autoloader.generated.ts');

const loaders = [];
for (const module of manifest.modules ?? []) {
	for (const declaration of module.declarations ?? []) {
		if (!declaration.customElement || !declaration.tagName) continue;
		const path = module.path.replace(/^src\//, '../').replace(/\.ts$/, '.js');
		loaders.push([declaration.tagName, path]);
	}
}
loaders.sort(([a], [b]) => a.localeCompare(b));

const output = `// Generated by scripts/generate-autoloader.js. Do not edit.

/** Per nldd-* tag, a dynamic import of the module that defines it. */
export const loaders: Record<string, () => Promise<unknown>> = {
${loaders.map(([tag, path]) => `\t'${tag}': () => import('${path}'),`).join('\n')}
};
`;

writeFileSync(outputPath, output);
console.log(`Wrote ${outputPath.replace(`${repoRoot}/`, '')} (${loaders.length} tags)`);
